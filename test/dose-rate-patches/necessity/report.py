"""Patch-necessity report (RunAll.ps1, ticket 07).

  report.py --sufficiency <dir with sufficiency-<N>.json> --necessity <work dir>
            --settings necessity.json --out <report.md>

Writes <report.md> and <report>.json: per patch, the sufficiency values on the
kernel without and with the patch, the leave-one-out necessity verdict of every
config, and the report-only G(beam-off) deltas. Prints one line per check and
exits 0 only when every sufficiency and every necessity demonstration holds (a
patch's necessity holds when at least one config demonstrates it).
"""
import argparse
import json
import os
import sys

PATCHES = {"1": ("finder-coincident", "coincident-neighbors.patch"),
           "2": ("source-contact", "source-contacts-experimental.patch"),
           "3": ("rebound-fold", "rebound-fold.patch")}


def load(path):
    with open(path, encoding="utf-8-sig") as handle:
        return json.load(handle)


def main(argv=None):
    p = argparse.ArgumentParser()
    p.add_argument("--sufficiency", required=True)
    p.add_argument("--necessity", required=True)
    p.add_argument("--settings", required=True)
    p.add_argument("--out", required=True)
    a = p.parse_args(argv)
    settings = load(a.settings)
    configs = list(settings["configs"])
    report = {"formatVersion": 1, "patches": {}}
    lines, md = [], ["# Dose-rate patch necessity report", "",
                     "Generated by `test/dose-rate-patches/RunAll.ps1`. Summary and caveats: "
                     "`docs/dose-rate-pulse-study/patch-necessity.md`.", ""]
    ok_all = True
    md += ["## Sufficiency (fixtures)", "", "| Patch | Kernel | Expect | Verdict | Values |", "|---|---|---|---|---|"]
    for n, (label, patch) in PATCHES.items():
        path = os.path.join(a.sufficiency, "sufficiency-%s.json" % n)
        suf = load(path) if os.path.exists(path) else None
        holds = bool(suf) and bool(suf.get("pass")) and all(
            r.get("verdict") == "PASS" for r in suf["variants"].values())
        report["patches"][n] = {"label": label, "patch": patch, "sufficiency": suf, "sufficiencyHolds": holds}
        for kernel, r in ((suf or {}).get("variants") or {}).items():
            values = ", ".join("%s=%s" % kv for kv in (r.get("values") or {}).items())
            md.append("| %s | %s | %s | %s | %s |" % (n, kernel, r.get("expect"), r.get("verdict"), values))
        lines.append("sufficiency %s: %s" % (label, "PASS" if holds else "FAIL"))
        ok_all &= holds
    md += ["", "## Necessity (leave-one-out histories)", ""]
    nec = {}
    for c in configs:
        path = os.path.join(a.necessity, c, "necessity-results.json")
        nec[c] = load(path) if os.path.exists(path) else None
        s = settings["configs"][c]
        md.append("- `%s`: %s Gy/s to %s Gy, %s realizations per kernel" % (
            c, s["rates"][0], s["doseGy"], list(s["realizations"].values())[0]))
    md += ["", "| Patch | Config | Result | Verdict |", "|---|---|---|---|"]
    for n, (label, _) in PATCHES.items():
        per = {}
        for c in configs:
            v = (nec[c] or {}).get("verdicts", {}).get("patch" + n)
            per[c] = v
            md.append("| %s | %s | %s | %s |" % (n, c, v["line"] if v else "missing",
                                                  ("PASS" if v["pass"] else "NOT DEMONSTRATED") if v else "-"))
        holds = any(v and v["pass"] for v in per.values())
        report["patches"][n]["necessity"] = per
        report["patches"][n]["necessityHolds"] = holds
        lines.append("necessity %s: %s" % (label, "PASS" if holds else "NOT DEMONSTRATED"))
        ok_all &= holds
    md += ["", "## G(beam-off) delta, report only (all - variant, per 100 eV)", ""]
    for c in configs:
        for variant, rows in ((nec[c] or {}).get("gBeamOffDelta") or {}).items():
            md += ["### %s, all - %s" % (c, variant), "", "| Species | all | %s | delta | z |" % variant,
                   "|---|---|---|---|---|"]
            for r in rows:
                if r["refMean"] == 0 and r["variantMean"] == 0:
                    continue
                md.append("| %s | %.4f | %.4f | %+.4f | %.2f |" % (
                    r["species"], r["refMean"], r["variantMean"], r["delta"], r["z"]))
            md.append("")
    report["gBeamOffDelta"] = {c: (nec[c] or {}).get("gBeamOffDelta") for c in configs}
    report["allHold"] = ok_all
    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    with open(a.out, "w", encoding="utf-8") as handle:
        handle.write("\n".join(md) + "\n")
    with open(os.path.splitext(a.out)[0] + ".json", "w", encoding="utf-8") as handle:
        json.dump(report, handle, indent=1)
    print("\n".join(lines))
    print("report: " + a.out)
    return 0 if ok_all else 1


if __name__ == "__main__":
    sys.exit(main())
