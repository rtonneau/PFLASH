#!/usr/bin/env python
"""Write one doseCutoff history config per dose rate and realization, plus plan.json.

Usage:
    python make_configs.py --library <capture library dir> --study study.json --out <plan dir>
                           [--output-root <dir>] [--realizations RATE=N ...] [--snapshots]

Every run gets distinct chemistry and source seeds (chemistrySeedBase + k, sourceSeedBase + k,
k counting all runs of all rates in order). The library may be shared by all runs; each run starts
at its own packet offset (`firstPacket`), drawn uniformly (PCG64 seeded by sourceSeedBase) among
the offsets from which the library still holds the target dose plus one maximum track, so that
`history` never runs out of packets. `--realizations 0.1=4 1e4=20` overrides study.json.
"""
import argparse
import csv
import json
import os
import sys

import numpy as np

DEFAULTS = {
    "doseGy": 1.0,
    "halfBoxUm": 2.0,
    "worldHalfSideUm": 3.0,
    "steadyStateWindow": 50,
    "steadyStateTolerance": 0.05,
    "steadyStateMinMean": 0.0,
    "ageGridPointsPerDecade": 0,
    "chemistrySeedBase": 1000,
    "sourceSeedBase": 500000,
    "firstPacket": None,
    "maxArrivals": 100000,
    "progressIntervalS": 30,
    "wallTimeCapS": 2700,
}
MAX_SEED = 2147483647
EV_TO_J = 1.602176634e-19


def rate_key(rate):
    return "%g" % float(rate)


def box_mass_kg(half_box_um):
    return 1000.0 * (2.0 * half_box_um * 1e-6) ** 3


def target_energy_ev(dose_gy, half_box_um):
    return dose_gy * box_mass_kg(half_box_um) / EV_TO_J


def load_study(path, overrides=None):
    with open(path, encoding="utf-8") as handle:
        raw = json.load(handle)
    study = dict(DEFAULTS)
    study.update(raw)
    if "rates" not in study:
        raise ValueError("study.json: missing key 'rates'")
    study["rates"] = [float(r) for r in study["rates"]]
    if not study["rates"] or any(r <= 0 for r in study["rates"]):
        raise ValueError("study.json: rates must be positive")
    counts = {}
    given = dict(study.get("realizations", {}))
    given.update(overrides or {})
    for rate in study["rates"]:
        found = [k for k in given if float(k) == rate]
        if not found:
            raise ValueError("no realization count for rate %s" % rate_key(rate))
        n = int(given[found[-1]])
        if n < 0:
            raise ValueError("negative realization count for rate %s" % rate_key(rate))
        counts[rate_key(rate)] = n
    study["realizations"] = counts
    if study["doseGy"] <= 0 or study["halfBoxUm"] <= 0:
        raise ValueError("doseGy and halfBoxUm must be positive")
    return study


def feasible_offsets(deposits, target_ev):
    """Offsets i such that the packets from i hold target_ev plus one maximum-deposit track."""
    deposits = np.asarray(deposits, dtype=float)
    need = target_ev + deposits.max()
    tail = np.cumsum(deposits[::-1])[::-1]   # tail[i] = sum of deposits[i:]
    return np.nonzero(tail >= need)[0]


def build_runs(study, deposits, snapshots=False):
    """Pure: the run list (no files)."""
    target = target_energy_ev(study["doseGy"], study["halfBoxUm"])
    offsets = feasible_offsets(deposits, target)
    if len(offsets) == 0:
        raise ValueError("the library holds %.4g eV, less than the %.4g eV of %g Gy plus one track"
                         % (float(np.sum(deposits)), target, study["doseGy"]))
    rng = np.random.Generator(np.random.PCG64(int(study["sourceSeedBase"])))
    runs = []
    k = 0
    for rate in study["rates"]:
        key = rate_key(rate)
        for r in range(study["realizations"][key]):
            chem = int(study["chemistrySeedBase"]) + k
            src = int(study["sourceSeedBase"]) + k
            if not (1 <= chem <= MAX_SEED and 1 <= src <= MAX_SEED):
                raise ValueError("seed out of range for run %d" % k)
            first = study["firstPacket"]
            first = int(first) if first is not None else int(rng.choice(offsets))
            if first not in set(offsets.tolist()):
                raise ValueError("firstPacket %d cannot reach the target dose" % first)
            runs.append({"id": "r%s_%03d" % (key, r), "rate_Gy_s": rate, "realization": r,
                         "chemistrySeed": chem, "sourceSeed": src, "firstPacket": first,
                         "snapshots": bool(snapshots)})
            k += 1
    return runs


def config_text(study, run, library_path):
    lines = [
        "# generated by make_configs.py",
        "mode = doseCutoff",
        "libraryDir = %s" % library_path,
        "halfBoxUm = %r" % float(study["halfBoxUm"]),
        "worldHalfSideUm = %r" % float(study["worldHalfSideUm"]),
        "chemistrySeed = %d" % run["chemistrySeed"],
        "sourceSeed = %d" % run["sourceSeed"],
        "doseRateGyPerS = %r" % float(run["rate_Gy_s"]),
        "doseGy = %r" % float(study["doseGy"]),
        "firstPacket = %d" % run["firstPacket"],
        "maxArrivals = %d" % int(study["maxArrivals"]),
        "steadyStateWindow = %d" % int(study["steadyStateWindow"]),
        "steadyStateTolerance = %r" % float(study["steadyStateTolerance"]),
        "steadyStateMinMean = %r" % float(study["steadyStateMinMean"]),
        "ageGridPointsPerDecade = %d" % int(study["ageGridPointsPerDecade"]),
    ]
    if float(study["progressIntervalS"]) > 0:
        lines.append("progressIntervalS = %r" % float(study["progressIntervalS"]))
    if run["snapshots"]:
        lines.append("snapshots = true")
    return "\n".join(lines) + "\n"


def read_deposits(library_dir):
    with open(os.path.join(library_dir, "library.csv"), newline="", encoding="utf-8") as handle:
        rows = list(csv.DictReader(handle))
    if [int(r["packetIndex"]) for r in rows] != list(range(len(rows))):
        raise ValueError("library.csv packet indices are not 0..N-1")
    return [float(r["energyDepositEv"]) for r in rows]


def relpath_or_abs(path, start):
    try:
        return os.path.relpath(path, start).replace("\\", "/")
    except ValueError:
        return os.path.abspath(path).replace("\\", "/")


def parse_overrides(items):
    out = {}
    for item in items or []:
        rate, _, n = item.partition("=")
        if not n:
            raise ValueError("--realizations takes RATE=N, got %r" % item)
        out[rate] = int(n)
    return out


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--library", required=True)
    parser.add_argument("--study", required=True)
    parser.add_argument("--out", required=True)
    parser.add_argument("--output-root")
    parser.add_argument("--realizations", nargs="*")
    parser.add_argument("--snapshots", action="store_true", help="snapshots = true in every config")
    args = parser.parse_args(argv)
    if os.path.isdir(args.out) and os.listdir(args.out):
        print("make_configs: output directory is not empty: " + args.out, file=sys.stderr)
        return 2
    try:
        study = load_study(args.study, parse_overrides(args.realizations))
        deposits = read_deposits(args.library)
        runs = build_runs(study, deposits, args.snapshots)
    except (ValueError, OSError) as error:
        print("make_configs: " + str(error), file=sys.stderr)
        return 2
    output_root = args.output_root or os.path.join(args.out, "out")
    entries = []
    for run in runs:
        run_dir = os.path.join(args.out, "runs", run["id"])
        os.makedirs(run_dir, exist_ok=True)
        cfg = os.path.join(run_dir, "history.cfg")
        with open(cfg, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(config_text(study, run, relpath_or_abs(args.library, run_dir)))
        entries.append(dict(run, config=relpath_or_abs(cfg, args.out),
                            output=relpath_or_abs(os.path.join(output_root, run["id"]), args.out)))
    plan = {
        "formatVersion": 1,
        "library": relpath_or_abs(args.library, args.out),
        "librarySize": len(deposits),
        "libraryEnergyDeposit_eV": float(sum(deposits)),
        "boxMass_kg": box_mass_kg(study["halfBoxUm"]),
        "targetEnergy_eV": target_energy_ev(study["doseGy"], study["halfBoxUm"]),
        "study": {k: v for k, v in study.items()},
        "outputRoot": relpath_or_abs(output_root, args.out),
        "runs": entries,
    }
    with open(os.path.join(args.out, "plan.json"), "w", encoding="utf-8") as handle:
        json.dump(plan, handle, indent=2)
    print("plan: %d runs over %d rates, library %d packets" % (len(entries), len(study["rates"]), len(deposits)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
